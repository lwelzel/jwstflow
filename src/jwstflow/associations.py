"""Association files.

Stage-2/3 pipelines consume JSON association files. jwstflow can build them in
three ways (``association.mode`` in the YAML):

``per_exposure``
    One Level-2 association per science exposure; background / imprint
    members are attached with :class:`MemberRule` (header filters + keywords
    that must match the science exposure). This is the manual recipe from the
    jwst docs (``asn_from_list -r DMSLevel2bBase`` + editing members).
``group``
    One Level-3 association per group of exposures sharing ``group_by`` header
    keywords, with an explicit product-name template.
``official``
    Build a pool from the headers (``jwst.associations.mkpool``) and run the
    DMS rule sets. Reproduces what MAST delivers, including instrument-specific
    subtleties. Needs the ``jwst`` package.

The JSON written follows the documented association format, so it is readable
by any jwst version; ``jwst`` itself is only imported for ``official`` mode.
"""

from __future__ import annotations

import json
import logging
import os
import re
from collections import defaultdict
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .config.schema import AssociationConfig, MemberRule
from .data.discovery import FileRecord, match_filters

log = logging.getLogger(__name__)

DEFAULT_RULE = {2: "DMSLevel2bBase", 3: "DMS_Level3_Base"}
DEFAULT_SCIENCE_FILTERS = {
    2: {"IS_IMPRT": False},  # backgrounds are calibrated as their own products
    3: {"BKGDTARG": False, "IS_IMPRT": False},
}


@dataclass
class Association:
    """An association ready to be written."""

    name: str  # file stem, e.g. jw01234-o001_t001_nirspec_g395h-f290lp_spec3
    data: dict[str, Any]
    members: list[Path] = field(default_factory=list)  # every file referenced

    @property
    def filename(self) -> str:
        return f"{self.name}_asn.json"

    def write(self, directory: Path, *, relative: bool = True) -> Path:
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / self.filename
        data = json.loads(json.dumps(self.data))  # deep copy, JSON-safe
        for product in data["products"]:
            for member in product["members"]:
                p = Path(member["expname"])
                member["expname"] = (
                    os.path.relpath(p, directory) if relative and p.is_absolute() else str(p)
                )
        path.write_text(json.dumps(data, indent=2) + "\n")
        return path


