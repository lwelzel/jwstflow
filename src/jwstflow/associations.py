def build_associations(
    records: list[FileRecord], cfg: AssociationConfig, *, asn_type: str, stage: str
) -> list[Association]:
    if cfg.mode == "per_exposure":
        return per_exposure(records, cfg, asn_type=asn_type, stage=stage)
    if cfg.mode == "group":
        return grouped(records, cfg, asn_type=asn_type, stage=stage)
    return official(records, cfg, stage=stage)


def per_exposure(
    records: list[FileRecord], cfg: AssociationConfig, *, asn_type: str, stage: str
) -> list[Association]:
    filters = cfg.science_filters or DEFAULT_SCIENCE_FILTERS[2]
    rule = cfg.rule or DEFAULT_RULE[cfg.level]
    science = [r for r in records if match_filters(r.meta, filters)]
    out: list[Association] = []
    for sci in science:
        data = _skeleton(
            asn_type=asn_type,
            rule=rule,
            program=sci.get("PROGRAM", 0),
            asn_id=_asn_id(sci, 2),
            pool=f"jwstflow_{stage}",
        )
        members = [{"expname": str(sci.path.resolve()), "exptype": "science"}]
        paths = [sci.path]
        for mrule in cfg.members:
            for cand in records:
                if _matches_member(sci, cand, mrule):
                    members.append({"expname": str(cand.path.resolve()), "exptype": mrule.exptype})
                    paths.append(cand.path)
        data["products"].append({"name": sci.stem, "members": members})
        out.append(Association(f"{sci.stem}_{asn_type}", data, paths))
    return out


def grouped(
    records: list[FileRecord], cfg: AssociationConfig, *, asn_type: str, stage: str
) -> list[Association]:
    filters = cfg.science_filters or DEFAULT_SCIENCE_FILTERS[3]
    rule = cfg.rule or DEFAULT_RULE[cfg.level]
    science = [r for r in records if match_filters(r.meta, filters)]
    groups: dict[tuple[Any, ...], list[FileRecord]] = defaultdict(list)
    for r in science:
        groups[tuple(r.get(k) for k in cfg.group_by)].append(r)
    out: list[Association] = []
    used: set[str] = set()
    for key, recs in groups.items():
        first = recs[0]
        name = product_name(cfg.product_name, first)
        # the association file / task label must be unique per group even when the
        # product name is not (e.g. DMS-style IFU names without the grating: the
        # pipeline's cube_build appends the grating-filter suffix itself)
        label = name
        if label in used:
            label = sanitize(f"{name}_{'-'.join(str(v) for v in key if v is not None)}")
        used.add(label)
        data = _skeleton(
            asn_type=asn_type,
            rule=rule,
            program=first.get("PROGRAM", 0),
            asn_id=_asn_id(first, 3),
            pool=f"jwstflow_{stage}",
            target=sanitize(str(first.get("TARGPROP", "t001"))),
        )
        members = [{"expname": str(r.path.resolve()), "exptype": "science"} for r in recs]
        paths = [r.path for r in recs]
        for mrule in cfg.members:
            seen: set[Path] = set()
            for sci in recs:
                for cand in records:
                    if cand.path in seen or cand.path in paths:
                        continue
                    if _matches_member(sci, cand, mrule):
                        seen.add(cand.path)
                        members.append(
                            {"expname": str(cand.path.resolve()), "exptype": mrule.exptype}
                        )
                        paths.append(cand.path)
        data["products"].append({"name": name, "members": members})
        out.append(Association(f"{label}_{asn_type}", data, paths))
    return out


def official(records: list[FileRecord], cfg: AssociationConfig, *, stage: str) -> list[Association]:
    """Run the jwst association generator on a pool built from the file headers.

    The DMS rules expect Level-1b (``_uncal``) names and rewrite them to
    ``_rate``/``_cal`` themselves, so the pool is fed ``<stem>_uncal.fits``
    names and the generated member names are mapped back to the real files by
    exposure stem. Exposures the rules reject are reported at WARNING level.
    """
    try:
        from jwst.associations import AssociationRegistry, generate
        from jwst.associations.lib.utilities import constrain_on_candidates
        from jwst.associations.mkpool import mkpool
    except ImportError as exc:
        raise RuntimeError("association.mode=official needs the `jwst` package") from exc
    import jwst.associations.lib as asnlib

    if not records:
        return []
    which = cfg.official_rules or ("level2" if cfg.level == 2 else "level3")
    rules_file = Path(asnlib.__file__).parent / (
        "rules_level2b.py" if which == "level2" else "rules_level3.py"
    )
    pool = mkpool([str(r.path) for r in records])
    pool["filename"] = [f"{r.stem}_uncal.fits" for r in records]
    # mkpool fills these "pool-only" columns with constants (in DMS they come from
    # the proposal database, not from headers); recover them from the headers.
    pool["is_imprt"] = ["t" if r.meta.get("IS_IMPRT") else "f" for r in records]
    pool["pntgtype"] = [str(r.meta.get("PNTGTYPE") or "science").lower() for r in records]
    registry = AssociationRegistry(
        definition_files=[str(rules_file)],
        include_default=False,
        # same global constraint `asn_generate` applies: without it every
        # association is a "discovered" (aNNNN) candidate and level 2 drops them
        global_constraints=constrain_on_candidates(None),
    )
    asns = generate(pool, registry)
    by_stem = {r.stem: r.path.resolve() for r in records}
    out: list[Association] = []
    for asn in asns:
        _fname, serialized = asn.dump()
        data = json.loads(serialized)
        data["asn_pool"] = f"jwstflow_{stage}"
        paths: list[Path] = []
        for product in data.get("products", []):
            kept = []
            for member in product.get("members", []):
                stem = FileRecord(Path(member["expname"])).stem
                p = by_stem.get(stem)
                if p is None:
                    log.warning("official asn %s: member %s has no matching input; dropped", data.get("asn_id"), member["expname"])
                    continue
                member["expname"] = str(p)
                paths.append(p)
                kept.append(member)
            product["members"] = kept
        data["products"] = [pr for pr in data["products"] if pr["members"]]
        if not data["products"]:
            continue
        first = data["products"][0]["name"]
        out.append(Association(sanitize(f"{first}_{data.get('asn_type', 'asn')}"), data, paths))
    if not out:
        log.warning("official association generator produced no %s associations", which)
    return out


def write_all(asns: Iterable[Association], directory: Path, *, relative: bool = True) -> list[Path]:
    return [a.write(directory, relative=relative) for a in asns]


def members_of(asn_path: Path) -> list[Path]:
    """Member paths referenced by an association file on disk."""
    data = json.loads(Path(asn_path).read_text())
    base = Path(asn_path).parent
    out: list[Path] = []
    for product in data.get("products", []):
        for member in product.get("members", []):
            p = Path(member["expname"])
            out.append(p if p.is_absolute() else (base / p))
    return out


def summarize(data: Mapping[str, Any]) -> str:
    parts = []
    for product in data.get("products", []):
        counts: dict[str, int] = defaultdict(int)
        for m in product.get("members", []):
            counts[m.get("exptype", "?")] += 1
        parts.append(f"{product.get('name')}: " + ", ".join(f"{v} {k}" for k, v in counts.items()))
    return "; ".join(parts)
