def _skeleton(
    *,
    asn_type: str,
    rule: str,
    program: Any,
    asn_id: str,
    pool: str,
    target: str | None = None,
) -> dict[str, Any]:
    return {
        "asn_type": asn_type,
        "asn_rule": rule,
        "version_id": datetime.now(timezone.utc).strftime("%Y%m%dt%H%M%S"),
        "code_version": "jwstflow",
        "degraded_status": "No known degraded exposures in association.",
        "program": f"{int(program):05d}" if str(program).isdigit() else str(program),
        "constraints": "Generated by jwstflow",
        "asn_id": asn_id,
        "target": target or "t001",
        "asn_pool": pool,
        "products": [],
    }


def _optelem(rec: FileRecord) -> str:
    inst = str(rec.get("INSTRUME", "")).upper()
    if inst == "NIRSPEC":
        return f"{rec.get('GRATING', 'none')}-{rec.get('FILTER', 'none')}"
    if inst == "MIRI" and rec.get("CHANNEL"):
        return f"{rec.get('CHANNEL')}-{rec.get('BAND', 'none')}"
    return str(rec.get("FILTER", rec.get("GRATING", "none")))


class _SafeMap(dict):
    def __missing__(self, key: str) -> str:
        return "none"


def product_name(template: str, rec: FileRecord) -> str:
    values = _SafeMap({k: v for k, v in rec.meta.items()})
    values["OPTELEM"] = _optelem(rec)
    if "PROGRAM" in values:
        values["PROGRAM"] = f"{int(values['PROGRAM']):05d}" if str(values["PROGRAM"]).isdigit() else values["PROGRAM"]
    if "OBSERVTN" in values:
        values["OBSERVTN"] = f"{int(values['OBSERVTN']):03d}" if str(values["OBSERVTN"]).isdigit() else values["OBSERVTN"]
    name = template.format_map(values)
    return sanitize(name)


def sanitize(name: str) -> str:
    name = name.strip().lower()
    name = re.sub(r"[^a-z0-9_\-.]+", "-", name)
    return re.sub(r"-{2,}", "-", name).strip("-")


def _matches_member(science: FileRecord, cand: FileRecord, rule: MemberRule) -> bool:
    if cand.path == science.path:
        return False
    if not match_filters(cand.meta, rule.filters):
        return False
    for key in rule.match_on:
        if cand.get(key) != science.get(key):
            return False
    for key in rule.differ_on:
        if cand.get(key) == science.get(key):
            return False
    return True


def _asn_id(rec: FileRecord, level: int) -> str:
    obs = rec.get("OBSERVTN")
    if obs is not None and str(obs).isdigit():
        return f"o{int(obs):03d}"
    return "a2001" if level == 2 else "a3001"


